package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

const bcsReadyPluginName = "openomsi_bcs_bridge_ready.lua"

// Current BCS waits for the literal substring "] spawned at" in ~/.openomsi/game.log
// before it leaves its loading screen. A normal local openOMSI spawn writes that marker,
// but a player entering through --lan-join can receive the multiplayer vehicle without
// going through the local entry-point logger. This companion plugin restores only that
// observable compatibility signal, and only after openOMSI itself confirms that a player
// vehicle really exists.
const bcsReadyPluginSource = `-- BBS+OpenOmsi Multiplayer readiness compatibility
-- Generated by the Bridge. It does not replace or modify PeDePe's bbs.lua.
local sent = false

omsi.every(0.1, function()
  if sent or not omsi.has_vehicle() then
    return
  end
  sent = true
  omsi.log("[BBS bridge] spawned at multiplayer player vehicle ready")
end)
`

func prepareBCSReadyPlugin(cfg localConfig) error {
	if cfg.Game == "" {
		return nil
	}
	targetDir := filepath.Join(contentFolder(cfg), "Plugins")
	if cfg.Root != "" && samePath(resolveExistingParent(filepath.Join(cfg.Root, "Plugins")), resolveExistingParent(targetDir)) {
		return fmt.Errorf("use a pasta client dentro de OpenOMSI-BBS")
	}
	if err := os.MkdirAll(targetDir, 0755); err != nil {
		return err
	}
	target := filepath.Join(targetDir, bcsReadyPluginName)
	wanted := []byte(bcsReadyPluginSource)
	if old, err := os.ReadFile(target); err == nil && bytes.Equal(old, wanted) {
		return nil
	}
	return writeAtomic(target, wanted, 0600)
}
