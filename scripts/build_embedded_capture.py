#!/usr/bin/env python3
"""Compile our passive observer only; no vendor JAR/classes are embedded."""
import base64
import io
import json
from pathlib import Path
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'build-support/release222/bcs-events'

def build():
    profiles = json.loads((SOURCE / 'reviewed-bcs-classes.json').read_text())['profiles']
    properties = 'profiles=' + str(len(profiles)) + '\n'
    for index, profile in enumerate(profiles):
        properties += ''.join(f'profile.{index}.{name}={value}\n' for name, value in profile['classes'].items())
    with tempfile.TemporaryDirectory(prefix='bbs-capture-') as folder:
        classes = Path(folder)
        subprocess.run(['java', '--module', 'jdk.compiler/com.sun.tools.javac.Main', '--release', '8',
                        '-encoding', 'UTF-8', '-d', str(classes), str(SOURCE / 'EventProbe.java')], check=True)
        data = io.BytesIO()
        with zipfile.ZipFile(data, 'w', zipfile.ZIP_DEFLATED) as archive:
            entries = {'bcs-event-fingerprints.properties': properties.encode()}
            entries.update({p.relative_to(classes).as_posix(): p.read_bytes() for p in classes.rglob('*.class')})
            for name, content in sorted(entries.items()):
                info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                archive.writestr(info, content)
        encoded = base64.b64encode(data.getvalue()).decode()
        lines = ['package main', '', '// Generated by scripts/build_embedded_capture.py; only our observer and reviewed hashes.',
                 'const bcsCapturePayload =']
        lines += ['\t"' + encoded[i:i+100] + '"' + (' +' if i+100 < len(encoded) else '') for i in range(0, len(encoded), 100)]
        (ROOT / 'source/bcs_capture_payload.go').write_text('\n'.join(lines) + '\n')
        print(f'Embedded {len(entries)} owned observer entries ({len(data.getvalue())} bytes)')

if __name__ == '__main__':
    build()
